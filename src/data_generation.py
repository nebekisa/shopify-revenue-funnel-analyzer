def _daily_session_count(day_index: int, rng: np.random.Generator) -> int:
    """Sessions per day with weekend uplift and mild noise."""
    d = datetime.fromisoformat(cfg.SIMULATION_START) + timedelta(days=day_index)
    weekday = d.weekday()  # Mon=0 ... Sun=6
    base = cfg.BASE_DAILY_SESSIONS
    if weekday >= 5:
        base = int(base * cfg.WEEKEND_MULTIPLIER)
    noise = int(rng.normal(0, base * 0.08))
    return max(50, base + noise)


def generate_raw_events() -> dict[str, pd.DataFrame]:
    """
    Generate all four raw tables for the simulation window.

    Returns a dict of DataFrames keyed by table name.
    """
    rng = np.random.default_rng(cfg.RANDOM_SEED)
    start = datetime.fromisoformat(cfg.SIMULATION_START)

    traffic: list[dict] = []
    cart: list[dict] = []
    checkout: list[dict] = []
    orders: list[dict] = []

    # Pre-create a user pool so some users return across days.
    n_users = 4000
    user_ids = [f"usr_{i:06d}" for i in range(n_users)]

    for day in range(cfg.SIMULATION_DAYS):
        n_sessions = _daily_session_count(day, rng)
        for _ in range(n_sessions):
            # ~22% of sessions are returning users
            if rng.random() < 0.22:
                user_id = str(rng.choice(user_ids))
            else:
                user_id = _make_id("usr")

            session_id = _make_id("sess")
            device = _sample_device(rng)
            source = _sample_source(rng)

            # Random start time within the day, weighted toward business hours
            hour = int(np.clip(rng.normal(14, 4), 0, 23))
            minute = int(rng.integers(0, 60))
            second = int(rng.integers(0, 60))
            start_ts = start + timedelta(days=day, hours=hour,
                                         minutes=minute, seconds=second)

            result = _walk_session(rng, session_id, user_id, device, source, start_ts)
            traffic.extend(result.traffic_rows)
            cart.extend(result.cart_rows)
            checkout.extend(result.checkout_rows)
            orders.extend(result.order_rows)

    df_traffic = pd.DataFrame(traffic)
    df_cart = pd.DataFrame(cart)
    df_checkout = pd.DataFrame(checkout)
    df_orders = pd.DataFrame(orders)

    # ---------------------------------------------------------------
    # Deliberate data-quality imperfections (documented, not hidden).
    # These simulate real-world tracking issues. The DQ module reports
    # them; the staging SQL handles them defensively.
    # ---------------------------------------------------------------

    # 1. Missing traffic_source
    if not df_traffic.empty:
        mask = rng.random(len(df_traffic)) < cfg.DQ_MISSING_SOURCE_RATE
        df_traffic.loc[mask, "traffic_source"] = None

    # 2. Duplicate traffic rows (tracking double-fire)
    if not df_traffic.empty:
        n_dup = int(len(df_traffic) * cfg.DQ_DUPLICATE_TRAFFIC_RATE)
        if n_dup > 0:
            dup_idx = rng.choice(df_traffic.index, size=n_dup, replace=False)
            df_traffic = pd.concat(
                [df_traffic, df_traffic.loc[dup_idx]], ignore_index=True)

    # 3. Duplicate cart rows
    if not df_cart.empty:
        n_dup = int(len(df_cart) * cfg.DQ_DUPLICATE_CART_RATE)
        if n_dup > 0:
            dup_idx = rng.choice(df_cart.index, size=n_dup, replace=False)
            df_cart = pd.concat(
                [df_cart, df_cart.loc[dup_idx]], ignore_index=True)

    # 4. Invalid order statuses (typos / partial writes)
    if not df_orders.empty:
        mask = rng.random(len(df_orders)) < cfg.DQ_INVALID_ORDER_STATUS_RATE
        df_orders.loc[mask, "order_status"] = "unknwon"

    # 5. Orphan orders (order without a matching checkout session row)
    if not df_orders.empty and not df_checkout.empty:
        n_orphan = int(len(df_orders) * cfg.DQ_ORPHAN_ORDER_RATE)
        if n_orphan > 0:
            orphan_idx = rng.choice(df_orders.index, size=n_orphan, replace=False)
            # Corrupt session_id so it has no checkout
            df_orders.loc[orphan_idx, "session_id"] = [
                _make_id("sess_orphan") for _ in range(n_orphan)
            ]

    # 6. Shuffle timestamps slightly within each table to simulate
    #    out-of-order arrival. We sort by timestamp only when writing.
    for df in (df_traffic, df_cart, df_checkout, df_orders):
        if not df.empty:
            df["timestamp"] = pd.to_datetime(df["timestamp"], utc=True)

    logger.info("Generated sessions: %d",
                df_traffic["session_id"].nunique() if not df_traffic.empty else 0)
    logger.info("traffic=%d cart=%d checkout=%d orders=%d",
                len(df_traffic), len(df_cart), len(df_checkout), len(df_orders))

    return {
        "traffic_logs": df_traffic,
        "cart_actions": df_cart,
        "checkout_events": df_checkout,
        "orders": df_orders,
    }


def validation_report(tables: dict[str, pd.DataFrame]) -> pd.DataFrame:
    """
    Session-level funnel validation. This is what proves the generator
    is behaviorally realistic (not just random rows).
    """
    traffic = tables["traffic_logs"]
    cart = tables["cart_actions"]
    checkout = tables["checkout_events"]
    orders = tables["orders"]

    total_sessions = traffic["session_id"].nunique()
    atc_sessions = cart.loc[
        cart["action"] == "add_to_cart", "session_id"
    ].nunique() if not cart.empty else 0
    checkout_sessions = checkout["session_id"].nunique() if not checkout.empty else 0
    purchase_sessions = orders.loc[
        orders["order_status"] == "paid", "session_id"
    ].nunique() if not orders.empty else 0

    rows = [
        ("Total sessions", total_sessions),
        ("Product-view sessions", total_sessions),
        ("Add-to-cart sessions", atc_sessions),
        ("Checkout sessions", checkout_sessions),
        ("Purchase sessions", purchase_sessions),
    ]
    df = pd.DataFrame(rows, columns=["Stage", "Sessions"])
    df["Conversion from previous"] = [
        None,
        f"{total_sessions / max(total_sessions, 1):.2%}",
        f"{atc_sessions / max(total_sessions, 1):.2%}",
        f"{checkout_sessions / max(atc_sessions, 1):.2%}",
        f"{purchase_sessions / max(checkout_sessions, 1):.2%}",
    ]
    df["Cumulative conversion"] = [
        f"{total_sessions / max(total_sessions, 1):.2%}",
        f"{total_sessions / max(total_sessions, 1):.2%}",
        f"{atc_sessions / max(total_sessions, 1):.2%}",
        f"{checkout_sessions / max(total_sessions, 1):.2%}",
        f"{purchase_sessions / max(total_sessions, 1):.2%}",
    ]
    return df