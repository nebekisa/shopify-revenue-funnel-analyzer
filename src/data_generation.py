# ---------------------------------------------------------------------------
# Low-level helpers
# ---------------------------------------------------------------------------

def _make_id(prefix: str) -> str:
    return f"{prefix}_{uuid.uuid4().hex[:12]}"


def _sample_device(rng: np.random.Generator) -> str:
    return str(rng.choice(cfg.DEVICES, p=cfg.DEVICE_WEIGHTS))


def _sample_source(rng: np.random.Generator) -> str:
    return str(rng.choice(cfg.TRAFFIC_SOURCES, p=cfg.SOURCE_WEIGHTS))


def _sample_order_value(rng: np.random.Generator) -> float:
    """Right-skewed order value via log-normal."""
    return float(np.round(rng.lognormal(cfg.ORDER_VALUE_MEAN_LOG,
                                        cfg.ORDER_VALUE_SIGMA_LOG), 2))


def _jitter(ts: datetime, rng: np.random.Generator,
            min_sec: int = 5, max_sec: int = 900) -> datetime:
    return ts + timedelta(seconds=int(rng.integers(min_sec, max_sec)))


def _prob(base: float, *multipliers: float) -> float:
    """Apply multiplicative segment effects, clamped to [0, 1]."""
    p = base
    for m in multipliers:
        p *= m
    return float(np.clip(p, 0.0, 1.0))


# ---------------------------------------------------------------------------
# Session state machine
# ---------------------------------------------------------------------------

@dataclass
class SessionResult:
    """What a completed session walk produced."""
    traffic_rows: list[dict]
    cart_rows: list[dict]
    checkout_rows: list[dict]
    order_rows: list[dict]


def _walk_session(
    rng: np.random.Generator,
    session_id: str,
    user_id: str,
    device: str,
    source: str,
    start_ts: datetime,
) -> SessionResult:
    """
    Walk one session through the funnel, emitting events.

    State transitions use MODULATED probabilities so segments differ.
    Timing is monotonic (mostly) with occasional out-of-order jitter
    introduced deliberately in the clean-up pass.
    """
    traffic_rows: list[dict] = []
    cart_rows: list[dict] = []
    checkout_rows: list[dict] = []
    order_rows: list[dict] = []

    ts = start_ts
    source_for_row = source

    # ---- 1. Product view(s) ----
    n_views = 1
    if rng.random() < cfg.P_VIEW_MULTIPLE_PRODUCTS:
        n_views = int(rng.integers(2, 5))

    viewed_products: list[str] = []
    for _ in range(n_views):
        pid = f"{cfg.PRODUCT_ID_PREFIX}{rng.integers(1000, 1000 + cfg.N_PRODUCTS)}"
        viewed_products.append(pid)
        traffic_rows.append({
            "session_id": session_id,
            "user_id": user_id,
            "timestamp": ts,
            "traffic_source": source_for_row,
            "device": device,
            "product_id_viewed": pid,
        })
        ts = _jitter(ts, rng, 5, 120)

    # ---- 2. Add to cart? ----
    p_atc = _prob(
        cfg.P_ADD_TO_CART_GIVEN_VIEW,
        cfg.DEVICE_MULTIPLIERS[device]["atc"],
        cfg.SOURCE_MULTIPLIERS.get(source, {"atc": 1.0})["atc"],
    )
    added = rng.random() < p_atc

    in_cart: list[str] = []
    if added:
        # Add 1-3 products (subset of viewed + possibly new)
        n_add = int(rng.integers(1, 4))
        for i in range(n_add):
            pid = viewed_products[i % len(viewed_products)] \
                if i < len(viewed_products) \
                else f"{cfg.PRODUCT_ID_PREFIX}{rng.integers(1000, 1000 + cfg.N_PRODUCTS)}"
            cart_rows.append({
                "session_id": session_id,
                "user_id": user_id,
                "timestamp": ts,
                "action": "add_to_cart",
                "product_id": pid,
            })
            in_cart.append(pid)
            ts = _jitter(ts, rng, 10, 240)

        # Possibly remove one
        if rng.random() < cfg.P_REMOVE_FROM_CART and in_cart:
            removed = in_cart.pop(int(rng.integers(0, len(in_cart))))
            cart_rows.append({
                "session_id": session_id,
                "user_id": user_id,
                "timestamp": ts,
                "action": "remove_from_cart",
                "product_id": removed,
            })
            ts = _jitter(ts, rng, 10, 240)

        # If cart emptied, stop here.
        if not in_cart:
            added = False

    # ---- 3. Checkout? ----
    reached_checkout = False
    checkout_id: str | None = None
    payment_attempted = False
    if added:
        p_checkout = _prob(
            cfg.P_CHECKOUT_GIVEN_CART,
            cfg.DEVICE_MULTIPLIERS[device]["checkout"],
            cfg.SOURCE_MULTIPLIERS.get(source, {"checkout": 1.0})["checkout"],
        )
        reached_checkout = rng.random() < p_checkout

    if reached_checkout:
        cart_value = float(np.round(
            sum(_sample_order_value(rng) for _ in in_cart), 2))
        checkout_id = _make_id("co")
        checkout_rows.append({
            "checkout_id": checkout_id,
            "session_id": session_id,
            "user_id": user_id,
            "timestamp": ts,
            "checkout_status": "checkout_started",
            "cart_value": cart_value,
        })
        ts = _jitter(ts, rng, 15, 300)

        # Payment attempted?
        if rng.random() < cfg.P_PAYMENT_ATTEMPTED_GIVEN_CHECKOUT:
            payment_attempted = True
            checkout_rows.append({
                "checkout_id": checkout_id,
                "session_id": session_id,
                "user_id": user_id,
                "timestamp": ts,
                "checkout_status": "payment_attempted",
                "cart_value": cart_value,
            })
            ts = _jitter(ts, rng, 10, 180)

    # ---- 4. Purchase? ----
    purchased = False
    if payment_attempted:
        p_purchase = _prob(
            cfg.P_PURCHASE_GIVEN_PAYMENT_ATTEMPTED,
            cfg.DEVICE_MULTIPLIERS[device]["purchase"],
            cfg.SOURCE_MULTIPLIERS.get(source, {"purchase": 1.0})["purchase"],
        )
        purchased = rng.random() < p_purchase

    if purchased:
        order_value = _sample_order_value(rng)
        discount = 0.0
        if rng.random() < cfg.DISCOUNT_PROBABILITY:
            lo, hi = cfg.DISCOUNT_RANGE
            discount = float(np.round(order_value * rng.uniform(lo, hi), 2))

        status = str(rng.choice(
            list(cfg.ORDER_STATUS_WEIGHTS.keys()),
            p=list(cfg.ORDER_STATUS_WEIGHTS.values()),
        ))

        # One order row per purchased product (typical Shopify line-item shape)
        for pid in in_cart:
            order_rows.append({
                "order_id": _make_id("ord"),
                "session_id": session_id,
                "user_id": user_id,
                "timestamp": ts,
                "gross_revenue": order_value,
                "discount_applied": discount,
                "product_id": pid,
                "order_status": status,
            })
    else:
        # Payment failed (if we attempted) — record the failure
        if payment_attempted and checkout_id is not None:
            checkout_rows.append({
                "checkout_id": checkout_id,
                "session_id": session_id,
                "user_id": user_id,
                "timestamp": ts,
                "checkout_status": "payment_failed",
                "cart_value": cart_value,  # noqa: F821  (defined above when payment_attempted)
            })

    return SessionResult(traffic_rows, cart_rows, checkout_rows, order_rows)


