"""
Synthetic Shopify-like event generator.

Design principle: behavior is MODELED, not sampled independently per row.
A session is generated by walking a state machine; events are emitted along
the walk. This is what makes the funnel internally consistent (e.g., a
purchase always has a preceding checkout_started event).
"""
from __future__ import annotations

import logging
import uuid
from dataclasses import dataclass
from datetime import datetime, timedelta
from typing import Iterator

import numpy as np
import pandas as pd
from faker import Faker

from src import config as cfg
from src.utils import get_logger

